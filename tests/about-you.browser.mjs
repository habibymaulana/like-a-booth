import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';
const b = await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const p = await b.newPage();
await p.goto('http://127.0.0.1:5173/frames');
const photos = [1,2,3,4].map(i=>'data:image/jpeg;base64,'+readFileSync(`artifacts/custom/reconstruction/photo-${i}.jpg`).toString('base64'));
const data = await p.evaluate(async photos=>{const {compose,frames}=await import('/src/engine.js');const c=document.createElement('canvas');await compose(c,frames.find(f=>f.id==='about-you'),photos);return c.toDataURL();},photos);
writeFileSync(`artifacts/about-you/${process.argv[2]||'after'}.png`,Buffer.from(data.split(',')[1],'base64'));
await p.getByRole('heading',{name:'About You',exact:true}).click();
await p.getByRole('button',{name:'Try Editor',exact:true}).click();
await p.waitForFunction(()=>document.querySelector('.editor-preview canvas')?.width===887);
await p.locator('.editor-preview canvas').screenshot({path:'artifacts/about-you/art-lab.png'});
const preview=await p.locator('.editor-preview canvas').evaluate(c=>c.toDataURL());
await p.getByRole('button',{name:'Preview finished artwork',exact:true}).click();
await p.waitForURL('**/result');
assert.equal(await p.locator('.result-image img').getAttribute('src'),preview);
await p.locator('.result-image').screenshot({path:'artifacts/about-you/results.png'});
const pending=p.waitForEvent('download');
await p.getByRole('link',{name:'Download PNG',exact:true}).click();
await (await pending).saveAs('artifacts/about-you/download.png');
assert.equal(readFileSync('artifacts/about-you/download.png').toString('base64'),preview.split(',')[1]);
console.log('Art Lab, Results and downloaded PNG match exactly.');
await b.close();
